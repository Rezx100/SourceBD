#!/usr/bin/env node
// One-off: the HS photo catalogue → the app.
//
//   node scripts/build-hs-photos.mjs            # write photos + lib/hs-catalogue.ts
//   node scripts/build-hs-photos.mjs --check    # exit 1 when the outputs are stale
//
// Reads `design/assets/products/hs/manifest.json` (46 four-digit EPB HS
// headings with an illustrative photo each) and the source files beside it
// (`hs/hs-<code>.png` or `aboni-knitwear/hs-<code>.min.webp`), and writes
//
//   public/products/hs/hs-<code>.webp        512 × 512, the sheet and strip tile
//   public/products/hs/hs-<code>-128.webp    128 × 128, the table thumb
//   lib/hs-catalogue.ts                       { hs, short, heading, exporters, hasPhoto }
//
// Resizing uses the Playwright Chromium already in devDependencies (a canvas
// in a headless page) — `sharp` is not a dependency of this repo (handoff §6).
// A heading whose source file is missing keeps its catalogue row with
// `hasPhoto: false`; nothing is substituted.
//
// Every source file is committed: the manifest, the 12 `aboni-knitwear/*.min.webp`
// and the 34 `hs/hs-<code>.png` renders. The 512/128 webp this writes are committed
// too, so a fresh clone serves every photo without re-running this.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ASSETS = path.join(ROOT, "design/assets/products");
const OUT_DIR = path.join(ROOT, "public/products/hs");
const CATALOGUE_TS = path.join(ROOT, "lib/hs-catalogue.ts");
const SIZES = [512, 128];
const CHECK = process.argv.includes("--check");

const manifest = JSON.parse(readFileSync(path.join(ASSETS, "hs/manifest.json"), "utf8"));

function sourceFile(code) {
  for (const f of [
    path.join(ASSETS, `hs/hs-${code}.png`),
    path.join(ASSETS, `hs/hs-${code}.min.webp`),
    path.join(ASSETS, `aboni-knitwear/hs-${code}.min.webp`),
  ]) {
    if (existsSync(f)) return f;
  }
  return null;
}

function outName(code, size) {
  return size === 512 ? `hs-${code}.webp` : `hs-${code}-${size}.webp`;
}

const rows = manifest.products
  .map((p) => ({
    hs: String(p.hs),
    short: p.short,
    heading: p.heading,
    exporters: Number(p.exporters),
    source: sourceFile(String(p.hs)),
  }))
  .sort((a, b) => a.hs.localeCompare(b.hs));

const catalogueTs = `// GENERATED by scripts/build-hs-photos.mjs from design/assets/products/hs/manifest.json
// (queried ${manifest.queried_at}). Do not edit by hand; re-run the script.
//
// One row per 4-digit EPB HS heading in the photo catalogue. \`exporters\` is the
// count of Bangladeshi exporters on the EPB list for that heading at query time,
// used to order a supplier's lines rarest-first. \`hasPhoto\` is whether
// public/products/hs/hs-<code>.webp exists; a heading without one renders its
// code, never a substitute photo.

export type HsCatalogueRow = {
  hs: string;
  short: string;
  heading: string;
  exporters: number;
  hasPhoto: boolean;
};

export const HS_CATALOGUE: readonly HsCatalogueRow[] = [
${rows
  .map(
    (r) =>
      `  { hs: ${JSON.stringify(r.hs)}, short: ${JSON.stringify(r.short)}, heading: ${JSON.stringify(
        r.heading,
      )}, exporters: ${r.exporters}, hasPhoto: ${r.source ? "true" : "false"} },`,
  )
  .join("\n")}
];
`;

if (CHECK) {
  const current = existsSync(CATALOGUE_TS) ? readFileSync(CATALOGUE_TS, "utf8") : "";
  const missing = rows
    .filter((r) => r.source)
    .flatMap((r) => SIZES.map((s) => outName(r.hs, s)))
    .filter((f) => !existsSync(path.join(OUT_DIR, f)));
  if (current !== catalogueTs || missing.length) {
    console.error(
      `hs-catalogue stale: ${current !== catalogueTs ? "lib/hs-catalogue.ts differs; " : ""}${missing.length} photo file(s) missing`,
    );
    process.exit(1);
  }
  console.log(`hs-catalogue up to date: ${rows.length} headings, ${rows.filter((r) => r.source).length} with a photo`);
  process.exit(0);
}

mkdirSync(OUT_DIR, { recursive: true });
// A machine whose Playwright browser build differs from the pinned one can
// point at any Chromium binary instead of downloading.
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined;
const browser = await chromium.launch(executablePath ? { executablePath } : {});
const page = await browser.newPage();
let written = 0;
for (const r of rows) {
  if (!r.source) continue;
  const mime = r.source.endsWith(".png") ? "image/png" : "image/webp";
  const dataUri = `data:${mime};base64,${readFileSync(r.source).toString("base64")}`;
  for (const size of SIZES) {
    const out = await page.evaluate(
      async ({ src, size }) => {
        const img = new Image();
        img.src = src;
        await img.decode();
        const canvas = document.createElement("canvas");
        canvas.width = size;
        canvas.height = size;
        const ctx = canvas.getContext("2d");
        // Cover-crop to a square from the centre, matching the tile's object-fit.
        const side = Math.min(img.naturalWidth, img.naturalHeight);
        const sx = (img.naturalWidth - side) / 2;
        const sy = (img.naturalHeight - side) / 2;
        ctx.imageSmoothingQuality = "high";
        ctx.drawImage(img, sx, sy, side, side, 0, 0, size, size);
        return canvas.toDataURL("image/webp", size >= 512 ? 0.82 : 0.78);
      },
      { src: dataUri, size },
    );
    const bytes = Buffer.from(out.split(",")[1], "base64");
    writeFileSync(path.join(OUT_DIR, outName(r.hs, size)), bytes);
    written += 1;
  }
}
await browser.close();
writeFileSync(CATALOGUE_TS, catalogueTs);
console.log(
  `wrote ${written} photo files for ${rows.filter((r) => r.source).length} of ${rows.length} headings, and lib/hs-catalogue.ts`,
);
